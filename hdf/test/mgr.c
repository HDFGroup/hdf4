    status = GRwritelut(pal_id, num_comp, data_type, interlace_mode, num_entries, (void *)palette_data);
    CHECK(status, FAIL, "GRgetlutid");

    status = GRendaccess(ri_id);
    CHECK(status, FAIL, "GRendaccess");
    ri_id = FAIL;

